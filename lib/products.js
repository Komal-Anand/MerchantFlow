export function filterProducts(products, filters) {
  return products.filter(p => {
    // Category filter — skip when 'all' or empty
    if (filters.category && filters.category !== 'all' && p.category !== filters.category) return false;

    // Price-range filter — resolve named range to min/max
    if (filters.priceRange && filters.priceRange !== 'all') {
      const range = PRICE_RANGES.find(r => r.id === filters.priceRange);
      if (range) {
        if (p.price < range.min || p.price > range.max) return false;
      }
    }

    // Explicit min/max (kept for backwards compat)
    if (filters.minPrice && p.price < filters.minPrice) return false;
    if (filters.maxPrice && p.price > filters.maxPrice) return false;

    // Search query
    if (filters.query && !p.name.toLowerCase().includes(filters.query.toLowerCase()) && !p.description.toLowerCase().includes(filters.query.toLowerCase())) return false;

    return true;
  });
}

export function sortProducts(products, sort) {
  const sorted = [...products];
  if (sort === 'price-low') sorted.sort((a, b) => a.price - b.price);
  if (sort === 'price-high') sorted.sort((a, b) => b.price - a.price);
  if (sort === 'rating') sorted.sort((a, b) => b.rating - a.rating);
  return sorted;
}
